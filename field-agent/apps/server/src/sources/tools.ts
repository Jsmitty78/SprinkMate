import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { evaluateLocalPlanGeometry, LocalGeometryInputError, type Fact, type LocalLength, type LocalPlanGeometry } from '@field-agent/core';
import { spearsCatalog, ELBOW_ID, PIPE_ID, type Catalog } from '@field-agent/fabrication';

/**
 * Validated calculation tools for Ask Sprink.
 *
 * Each tool wraps an existing script (no new engineering math is written here) behind a fixed
 * input schema. The question text only chooses which tool to call; inputs come from the work
 * package, the product catalog, or values the user typed, and every input is checked for units,
 * presence and the script's supported scope before the script runs. Nothing generated by a model
 * is ever executed.
 */

export type Origin = 'project' | 'sample' | 'you' | 'derived' | 'catalog';
export interface ToolInput { name: string; label: string; value: number | string | null; unit: string | null; origin: Origin; detail: string }
export interface ToolOutput { name: string; label: string; value: number | string | null; unit: string | null }
export interface CalculationResult {
  toolId: string; title: string;
  script: { module: string; fn: string; version: string };
  status: 'ok' | 'missing_inputs' | 'out_of_scope' | 'invalid_input';
  inputs: ToolInput[]; outputs: ToolOutput[]; missing: string[]; message: string;
  /** Always shown with the result: a calculation is not a compliance finding. */
  limits: string;
  ms: number;
}

const GEOMETRY_FILE = new URL('../../../../packages/core/src/local-change-geometry.ts', import.meta.url);
let cachedVersion: string | null = null;
/** The script version is the content hash of the file that implements it, so it changes when the math does. */
export function geometryScriptVersion(): string {
  if (!cachedVersion) {
    try { cachedVersion = `sha256:${createHash('sha256').update(readFileSync(fileURLToPath(GEOMETRY_FILE))).digest('hex').slice(0, 12)}`; }
    catch { cachedVersion = 'unavailable'; }
  }
  return cachedVersion;
}
const SCRIPT = () => ({ module: '@field-agent/core/local-change-geometry', fn: 'evaluateLocalPlanGeometry', version: geometryScriptVersion() });
const known = <T>(value: T, ids: string[]): Fact<T> => ({ value, confirmed: true, evidenceIds: ids, source: 'manual' });
const TO_MM: Record<string, number> = { mm: 1, m: 1000, in: 25.4, ft: 304.8 };
const MAX_MM = 100_000;

export interface Point { x: number; y: number; z: number }
export interface Box { min: Point; max: Point }

export function toMm(value: number, unit: string): number | null {
  const f = TO_MM[unit];
  return f && Number.isFinite(value) ? value * f : null;
}

// ------------------------------------------------------------------ pipe-to-duct clearance

export interface ClearanceArgs {
  segment: { id: string; start: Point | null; end: Point | null; origin: Origin; detail: string } | null;
  duct: { box: Box | null; origin: Origin; detail: string } | null;
  /** Vertical move of the pipe the user asked about (negative = down), in mm. */
  verticalOffsetMm: { value: number; origin: Origin; detail: string } | null;
}

export function pipeDuctClearance(args: ClearanceArgs): CalculationResult {
  const t0 = performance.now();
  const catalog = spearsCatalog('ask-sprink');
  const pipe = pipeOf(catalog);
  const odIn = pipe.outsideDiameter.value;
  const inputs: ToolInput[] = [];
  const missing: string[] = [];
  const base = {
    toolId: 'pipe_duct_clearance', title: 'Pipe to duct clearance (geometry only)', script: SCRIPT(),
    limits: 'Geometry only: the gap between the pipe surface and the measured duct box. It does not check sprinkler discharge obstruction, supports, or any code requirement, and it is not a compliance result.',
  };
  const seg = args.segment;
  if (!seg?.start || !seg.end) missing.push('Pipe endpoints for the selected piece');
  if (!args.duct?.box) missing.push('Measured duct box (all six faces)');
  if (missing.length) return { ...base, status: 'missing_inputs', inputs, outputs: [], missing, message: 'The calculation needs the inputs listed.', ms: performance.now() - t0 };

  const dz = args.verticalOffsetMm?.value ?? 0;
  if (!Number.isFinite(dz) || Math.abs(dz) > MAX_MM) return { ...base, status: 'invalid_input', inputs, outputs: [], missing, message: 'The vertical move must be a finite length under 100 m.', ms: performance.now() - t0 };
  const s = { ...seg!.start!, z: seg!.start!.z + dz }, e = { ...seg!.end!, z: seg!.end!.z + dz };
  const box = args.duct!.box!;
  const fmt = (p: Point) => `(${p.x}, ${p.y}, ${p.z})`;
  inputs.push(
    { name: 'pipeStart', label: `Piece ${seg!.id} start`, value: fmt(seg!.start!), unit: 'mm', origin: seg!.origin, detail: seg!.detail },
    { name: 'pipeEnd', label: `Piece ${seg!.id} end`, value: fmt(seg!.end!), unit: 'mm', origin: seg!.origin, detail: seg!.detail },
    { name: 'ductMin', label: 'Duct box minimum corner', value: fmt(box.min), unit: 'mm', origin: args.duct!.origin, detail: args.duct!.detail },
    { name: 'ductMax', label: 'Duct box maximum corner', value: fmt(box.max), unit: 'mm', origin: args.duct!.origin, detail: args.duct!.detail },
    { name: 'outsideDiameter', label: 'Pipe outside diameter (CP-010)', value: odIn, unit: 'in', origin: 'catalog', detail: 'Spears FlameGuard General Information, CP-010 row (catalog source record)' },
  );
  if (dz) inputs.push({ name: 'verticalOffset', label: 'Vertical move you asked about', value: dz, unit: 'mm', origin: args.verticalOffsetMm!.origin, detail: args.verticalOffsetMm!.detail });

  const frame = 'ask-frame';
  const pt = (p: Point) => ({ ...p, unit: 'mm' as const, frameId: frame });
  const geometry: LocalPlanGeometry = {
    id: 'ask-clearance',
    coordinateFrame: known({ id: frame, lengthUnit: 'mm' as const }, ['ask-context']),
    nodes: [
      { id: 'a', kind: 'other', position: known(pt(s), ['ask-pipe']) },
      { id: 'b', kind: 'other', position: known(pt(e), ['ask-pipe']) },
    ],
    segments: [{
      id: seg!.id, startNodeId: 'a', endNodeId: 'b',
      outsideDiameter: known<LocalLength>({ value: odIn, unit: 'in' }, ['catalog']),
      cutEndDatumAtStart: known('center_to_center' as const, ['ask-pipe']), cutEndDatumAtEnd: known('center_to_center' as const, ['ask-pipe']),
    }],
    fittings: [],
    ducts: [{ id: 'duct', roomId: 'work-area', geometry: known({ kind: 'axis_aligned_box' as const, min: pt(box.min), max: pt(box.max) }, ['ask-duct']) }],
  };
  try {
    const result = evaluateLocalPlanGeometry(geometry);
    const c = result.ductClearances[0];
    if (!c || c.state === 'unsupported') return { ...base, status: 'out_of_scope', inputs, outputs: [], missing, message: 'The script supports straight pipe along one axis and an axis-aligned duct box only.', ms: performance.now() - t0 };
    if (c.state === 'input_missing') return { ...base, status: 'missing_inputs', inputs, outputs: [], missing: c.missingInputs, message: 'The script reported missing inputs.', ms: performance.now() - t0 };
    const outputs: ToolOutput[] = [
      { name: 'state', label: 'Result', value: c.state === 'collision' ? 'Pipe intersects the duct box' : 'Pipe is clear of the duct box', unit: null },
      { name: 'surfaceGap', label: 'Gap from pipe surface to duct box', value: c.state === 'collision' ? 0 : round(c.marginM! * 1000), unit: 'mm' },
      { name: 'centerlineDistance', label: 'Centerline to duct box', value: round(c.distanceM! * 1000), unit: 'mm' },
    ];
    return { ...base, status: 'ok', inputs, outputs, missing, message: c.state === 'collision' ? 'The pipe envelope intersects the measured duct box.' : `The pipe surface is ${round(c.marginM! * 1000)} mm from the measured duct box.`, ms: performance.now() - t0 };
  } catch (error) {
    if (error instanceof LocalGeometryInputError) return { ...base, status: 'invalid_input', inputs, outputs: [], missing, message: error.message, ms: performance.now() - t0 };
    throw error;
  }
}

// ------------------------------------------------------------------ cut length between two elbows

export function straightCutLength(args: { centerToCenter: { value: number; unit: string; origin: Origin; detail: string } | null }): CalculationResult {
  const t0 = performance.now();
  const catalog = spearsCatalog('ask-sprink');
  const elbow = elbowOf(catalog);
  const rawFace = elbow.centerToFace, rawBottom = elbow.centerToSocketBottom;
  if (!rawFace || !rawBottom || rawFace.unit !== rawBottom.unit) return {
    toolId: 'straight_cut_length', title: 'Cut length between two 4206-010S elbows', script: SCRIPT(), status: 'out_of_scope', inputs: [], outputs: [], missing: [],
    message: 'The catalog has no confirmed elbow dimensions, so the cut cannot be calculated.', limits: '', ms: performance.now() - t0 };
  const face: LocalLength = rawFace as LocalLength, bottom: LocalLength = rawBottom as LocalLength;
  const insertion: LocalLength = { value: face.value - bottom.value, unit: face.unit };
  const base = {
    toolId: 'straight_cut_length', title: 'Cut length between two 4206-010S elbows', script: SCRIPT(),
    limits: 'Nominal cut from catalog dimensions. It does not include field allowances or the published ±1/32 in tolerance, and it is not a check that the piece or route is acceptable.',
  };
  const inputs: ToolInput[] = [
    { name: 'centerToFace', label: 'Elbow center to face (H)', value: face.value, unit: face.unit, origin: 'catalog', detail: 'Spears FG90S-2-0723, 4206-010S row (catalog source record)' },
    { name: 'socketDepth', label: 'Socket depth (H − G)', value: insertion.value, unit: insertion.unit, origin: 'catalog', detail: 'Spears FG90S-2-0723, G and H dimensions (catalog source record)' },
  ];
  const cc = args.centerToCenter;
  if (!cc) return { ...base, status: 'missing_inputs', inputs, outputs: [], missing: ['Center-to-center length'], message: 'Enter the center-to-center length between the two elbows.', ms: performance.now() - t0 };
  const mm = toMm(cc.value, cc.unit);
  if (mm === null) return { ...base, status: 'invalid_input', inputs, outputs: [], missing: [], message: `Unit "${cc.unit}" is not supported. Use mm, m, in or ft.`, ms: performance.now() - t0 };
  if (mm <= 0 || mm > MAX_MM) return { ...base, status: 'invalid_input', inputs, outputs: [], missing: [], message: 'The center-to-center length must be greater than 0 and under 100 m.', ms: performance.now() - t0 };
  inputs.unshift({ name: 'centerToCenter', label: 'Center to center', value: cc.value, unit: cc.unit, origin: cc.origin, detail: cc.detail });

  // A straight piece between two perpendicular elbows: stub, elbow, piece, elbow, stub.
  const frame = 'ask-frame', L = mm, stub = 300;
  const p = (x: number, y: number) => known({ x, y, z: 0, unit: 'mm' as const, frameId: frame }, ['ask-input']);
  const len = (l: LocalLength) => known(l, ['catalog']);
  const od = known<LocalLength>(pipeOf(catalog).outsideDiameter, ['catalog']);
  const datum = known('center_to_center' as const, ['ask-input']);
  const port = (segmentId: string, endpoint: 'start' | 'end', nodeId: string) => ({ segmentId, endpoint, nodeId, centerToFace: len(face), insertionOrThreadMakeup: len(insertion) });
  const geometry: LocalPlanGeometry = {
    id: 'ask-cut', coordinateFrame: known({ id: frame, lengthUnit: 'mm' as const }, ['ask-context']),
    nodes: [
      { id: 's0', kind: 'other', position: p(0, -stub) }, { id: 'e1', kind: 'fitting_center', fittingId: 'F1', position: p(0, 0) },
      { id: 'e2', kind: 'fitting_center', fittingId: 'F2', position: p(L, 0) }, { id: 's3', kind: 'other', position: p(L, stub) },
    ],
    segments: [
      { id: 'stub-a', startNodeId: 's0', endNodeId: 'e1', outsideDiameter: od, cutEndDatumAtStart: datum, cutEndDatumAtEnd: datum },
      { id: 'piece', startNodeId: 'e1', endNodeId: 'e2', outsideDiameter: od, cutEndDatumAtStart: datum, cutEndDatumAtEnd: datum },
      { id: 'stub-b', startNodeId: 'e2', endNodeId: 's3', outsideDiameter: od, cutEndDatumAtStart: datum, cutEndDatumAtEnd: datum },
    ],
    fittings: [
      { id: 'F1', kind: known('elbow_90' as const, ['catalog']), centerNodeId: 'e1', ports: [port('stub-a', 'end', 'e1'), port('piece', 'start', 'e1')] },
      { id: 'F2', kind: known('elbow_90' as const, ['catalog']), centerNodeId: 'e2', ports: [port('piece', 'end', 'e2'), port('stub-b', 'start', 'e2')] },
    ],
    ducts: [],
  };
  try {
    const result = evaluateLocalPlanGeometry(geometry);
    const seg = result.segments.find(s => s.segmentId === 'piece')!;
    if (seg.cutLengthM === null) return { ...base, status: 'missing_inputs', inputs, outputs: [], missing: seg.missingInputs, message: 'The script could not compute the cut.', ms: performance.now() - t0 };
    const cutMm = seg.cutLengthM * 1000;
    return { ...base, status: 'ok', inputs, missing: [], ms: performance.now() - t0,
      outputs: [
        { name: 'cutLength', label: 'Nominal cut length', value: round(cutMm), unit: 'mm' },
        { name: 'cutLengthIn', label: 'Nominal cut length', value: round(cutMm / 25.4, 3), unit: 'in' },
        { name: 'takeoutEach', label: 'Takeout at each elbow (G)', value: round((face.value - insertion.value) * 25.4), unit: 'mm' },
      ],
      message: `Nominal cut ${round(cutMm)} mm for ${cc.value} ${cc.unit} center to center.` };
  } catch (error) {
    if (error instanceof LocalGeometryInputError) return { ...base, status: 'invalid_input', inputs, outputs: [], missing: [], message: error.message, ms: performance.now() - t0 };
    throw error;
  }
}

type Product = Catalog['products'][number];
const pipeOf = (c: Catalog) => c.products.find((p): p is Extract<Product, { kind: 'pipe' }> => p.id === PIPE_ID && p.kind === 'pipe')!;
const elbowOf = (c: Catalog) => c.products.find((p): p is Extract<Product, { kind: 'elbow_90' }> => p.id === ELBOW_ID && p.kind === 'elbow_90')!;
const round = (n: number, digits = 1) => Math.round(n * 10 ** digits) / 10 ** digits;

